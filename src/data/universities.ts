export const featuredUniversitySeeds = universitySeeds.filter((university) => university.featured);

export const normalizeUniversitySearchText = (value: string) => {
  return value
    .trim()
    .toLowerCase()
    .replace(/\s/g, "")
    .replace(/대학교|대학|캠퍼스|campus/gi, "")
    .replace(/[^\w가-힣]/g, "");
};

export const findUniversityByName = (value: string) => {
  const normalized = normalizeUniversitySearchText(value);
  if (!normalized) return undefined;

  const exact = universitySeeds.find((university) => {
    const names = [university.name, university.shortName, ...university.aliases];
    return names.some((name) => normalizeUniversitySearchText(name) === normalized);
  });

  if (exact) return exact;

  return universitySeeds.find((university) => {
    const names = [university.name, university.shortName, ...university.aliases];
    return names.some((name) => {
      const normalizedName = normalizeUniversitySearchText(name);
      return normalizedName.includes(normalized) || normalized.includes(normalizedName);
    });
  });
};

export const normalizeUniversityName = (value: string) => {
  return findUniversityByName(value)?.name || value.trim();
};

export const getFeaturedUniversities = () => featuredUniversitySeeds;

export const searchUniversities = (keyword: string, limit = 10) => {
  const normalized = normalizeUniversitySearchText(keyword);
  const source = normalized ? universitySeeds : featuredUniversitySeeds;

  return source
    .filter((university) => {
      if (!normalized) return true;
      const names = [university.name, university.shortName, ...university.aliases];
      return names.some((name) => normalizeUniversitySearchText(name).includes(normalized));
    })
    .slice(0, limit);
};

export const suggestUniversitiesFromRawText = (rawText: string) => {
  const normalizedRaw = normalizeUniversitySearchText(rawText);
  if (!normalizedRaw) return [];

  return universitySeeds.filter((university) => {
    const names = [university.name, university.shortName, ...university.aliases];
    return names.some((name) => {
      const normalizedName = normalizeUniversitySearchText(name);
      return normalizedName.length >= 2 && normalizedRaw.includes(normalizedName);
    });
  });
};
